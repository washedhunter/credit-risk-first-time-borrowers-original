"""Write reports/metrics.json (everything) and reports/metrics.md (the README tables)."""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any

from credit_risk.scoring.feature_info import info

SEG_LABEL = {"overall": "All applicants", "thin_file": "Thin-file", "no_bureau": "No bureau record"}


def _clean(obj: Any) -> Any:
    if isinstance(obj, float):
        return None if math.isnan(obj) else round(obj, 6)
    if isinstance(obj, dict):
        return {k: _clean(v) for k, v in obj.items()}
    if isinstance(obj, list | tuple):
        return [_clean(v) for v in obj]
    return obj


def _pct(v: float | None, digits: int = 1) -> str:
    return (
        "n/a" if v is None or (isinstance(v, float) and math.isnan(v)) else f"{v * 100:.{digits}f}%"
    )


def _ci(m: dict, key: str) -> str:
    v = m.get(key)
    ci = m.get("ci95", {}).get(key)
    if v is None:
        return "n/a"
    return f"{v:.3f} [{ci[0]:.3f}, {ci[1]:.3f}]" if ci else f"{v:.3f}"


def render_markdown(r: dict) -> str:
    lines: list[str] = []
    add = lines.append
    run, data, ho = r["run"], r["data"], r["holdout"]
    add(
        f"<!-- generated by `credit-risk train` on {run['date']} (model {run['model_version']}) -->"
    )
    add("")
    add(
        f"Data: {run['rows']:,} applications, default rate {_pct(data['default_rate'])}. "
        f"Thin-file (no bureau record and no previous Home Credit application): {data['thin_file_n']:,} "
        f"({_pct(data['thin_file_n'] / run['rows'])}), default rate {_pct(data['thin_file_default_rate'])}. "
        f"Stratified hold-out: {run['holdout_rows']:,} applicants, of which {data['holdout_thin_file_n']} thin-file "
        f"({data['holdout_thin_file_defaults']} defaults). Brackets are bootstrap 95% CIs."
    )
    add("")
    add("**Hold-out metrics**")
    add("")
    add("| Segment | Model | n | ROC-AUC | PR-AUC | KS | Brier |")
    add("|---|---|---:|---|---|---|---|")
    for seg in ("overall", "no_bureau", "thin_file"):
        for model, label in (("baseline", "Logistic baseline"), ("lightgbm", "LightGBM")):
            m = ho[seg][model]
            add(
                f"| {SEG_LABEL[seg]} | {label} | {m['n']:,} | {_ci(m, 'roc_auc')} | {_ci(m, 'pr_auc')} | "
                f"{_ci(m, 'ks')} | {_ci(m, 'brier')} |"
            )
    oof_thin = r["oof_train"]["thin_file"]["lightgbm"]
    add("")
    add(
        f"Larger-sample check for thin-file: out-of-fold on the training split (n = {oof_thin['n']:,}, "
        f"{oof_thin['defaults']} defaults): ROC-AUC {_ci(oof_thin, 'roc_auc')}, PR-AUC {_ci(oof_thin, 'pr_auc')}, "
        f"KS {_ci(oof_thin, 'ks')}."
    )
    add("")
    imb = r["imbalance"]
    add(
        f"**Class imbalance** ({imb['negatives_per_positive']:.1f} repaid loans per default; out-of-fold on the training split; chosen: `{imb['chosen']}`)"
    )
    add("")
    add(
        "| scale_pos_weight | ROC-AUC | PR-AUC | Brier | Mean predicted | Cost-optimal threshold | Expected cost / application |"
    )
    add("|---|---|---|---|---|---|---|")
    for name, s in imb["strategies"].items():
        add(
            f"| {name} ({s['scale_pos_weight']:.2f}) | {s['roc_auc']:.4f} | {s['pr_auc']:.4f} | {s['brier']:.4f} | "
            f"{_pct(s['mean_predicted'])} | {s['best_threshold']:.3f} | {s['min_cost_per_application']:,.0f} |"
        )
    add("")
    c = r["cost_assumptions"]
    add(
        f"**Approval threshold** (approve when P(default) < {r['threshold']:.3f}). Costs: an approved defaulter loses "
        f"{c['loss_given_default']:.0%} of the loan amount; a rejected good customer costs {c['margin_good_loan']:.0%} "
        f"of the loan amount in lost margin (illustrative assumptions; break-even probability for a calibrated model "
        f"= {c['breakeven_probability']:.3f}). Chosen on out-of-fold predictions, reported on the hold-out:"
    )
    add("")
    add(
        "| Segment | Approval rate | Default rate, approved | Default rate, declined | Defaults caught | Good customers declined | Cost saving vs approve-all |"
    )
    add("|---|---|---|---|---|---|---|")
    for seg in ("overall", "no_bureau", "thin_file"):
        d = ho[seg]["decision"]
        add(
            f"| {SEG_LABEL[seg]} | {_pct(d['approval_rate'])} | {_pct(d['default_rate_approved'], 2)} | "
            f"{_pct(d['default_rate_rejected'])} | {_pct(d['defaults_caught'])} | {_pct(d['good_rejected'])} | "
            f"{_pct(d['saving_vs_approve_all'])} |"
        )
    add("")
    st = r["segment_thresholds"]
    add(
        "Segment-specific thresholds (chosen on out-of-fold data, not deployed): "
        + "; ".join(
            f"{SEG_LABEL[k]} {v['oof_optimal_threshold']:.3f} -> hold-out approval {_pct(v['holdout_at_segment_threshold']['approval_rate'])}, "
            f"default rate among approved {_pct(v['holdout_at_segment_threshold']['default_rate_approved'], 2)}"
            for k, v in st.items()
        )
        + "."
    )
    add("")
    add(
        "**Sensitivity to the cost assumptions** (threshold re-chosen on out-of-fold data each time; hold-out outcomes)"
    )
    add("")
    add(
        "| Loss given default | Lost margin | Threshold | Approval rate | Default rate, approved | Saving vs approve-all |"
    )
    add("|---|---|---|---|---|---|")
    for s in r["sensitivity"]:
        add(
            f"| {s['loss_given_default']:.0%} | {s['margin_good_loan']:.0%} | {s['threshold']:.3f} | {_pct(s['approval_rate'])} | "
            f"{_pct(s['default_rate_approved'], 2)} | {_pct(s['saving_vs_approve_all'])} |"
        )
    add("")
    add(
        "**Fairness audit** (hold-out; gender and age are not model inputs, used here only to check outcomes)"
    )
    add("")
    add(
        "| Attribute | Group | n | Actual default rate | Mean score | Approval rate | Default rate, approved |"
    )
    add("|---|---|---:|---|---|---|---|")
    for attr, rows in r["fairness_audit"].items():
        for row in rows:
            add(
                f"| {attr} | {row['group']} | {row['n']:,} | {_pct(row['default_rate'])} | {_pct(row['mean_score'])} | "
                f"{_pct(row['approval_rate'])} | {_pct(row['default_rate_approved'], 2)} |"
            )
    add("")
    add(
        "**Top features by mean |SHAP|** (hold-out sample of {:,})".format(r["shap"]["sample_size"])
    )
    add("")
    add("| # | Feature | Meaning | Mean \\|SHAP\\| |")
    add("|---:|---|---|---|")
    for i, f in enumerate(r["shap"]["top_features"][:15], start=1):
        add(f"| {i} | `{f['feature']}` | {info(f['feature']).label} | {f['mean_abs_shap']:.3f} |")
    add("")
    t = run["timings_s"]
    add(
        f"Run: {run['features']} features, {r['num_boost_round']} trees; total {t['total_s'] / 60:.1f} min on "
        f"{run['platform']} (Python {run['versions']['python']}, LightGBM {run['versions']['lightgbm']})."
    )
    return "\n".join(lines) + "\n"


def write_reports(results: dict, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    clean = _clean(results)
    (out_dir / "metrics.json").write_text(
        json.dumps(clean, indent=1) + "\n", encoding="utf-8", newline="\n"
    )
    (out_dir / "metrics.md").write_text(render_markdown(clean), encoding="utf-8", newline="\n")
